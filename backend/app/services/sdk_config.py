"""SDK配置领域服务：管理多语言SDK生成模板、认证方式和序列化格式。

跨模块数据流：
- 消费 api_registry 快照 → API注册信息用于SDK代码生成
- 消费 version_compat 快照 → 版本兼容映射用于SDK升级
- SDK配置变更 → 写共享快照通知下游
"""
from __future__ import annotations

from typing import Any

from app.services.base import BaseModuleService
from app.store import store


class SdkConfigService(BaseModuleService):
    MODULE = "sdk_config"
    ENTITY = "SDK配置"
    OPERATION_TERM = "关联"
    LIST_FIELDS = ["配置编号", "关联API", "SDK语言", "生成模板", "认证方式", "重试策略", "序列化格式", "配置版本"]
    REQUIRED_FIELDS = ["配置编号", "关联API", "SDK语言"]
    STATUS_ORDER = ["草稿", "待校验", "已发布", "已废弃"]
    ACTION_RULES = {"提交校验": "待校验", "确认发布": "已发布", "标记废弃": "已废弃"}
    NEGATIVE_ACTIONS = []

    def generate_sdk_code(self, sdk_id: int) -> str:
        """根据SDK配置生成代码模板。"""
        entry = store.find(self.MODULE, sdk_id)
        if entry is None:
            return ""

        language = entry.get("SDK语言", "python")
        template = entry.get("生成模板", "rest")
        auth = entry.get("认证方式", "apikey")
        retry = entry.get("重试策略", "exponential")
        serialization = entry.get("序列化格式", "json")

        # 根据语言和模板生成示例代码
        if language == "python":
            return self._generate_python_sdk(entry, auth, retry, serialization)
        elif language == "java":
            return self._generate_java_sdk(entry, auth)
        elif language == "typescript":
            return self._generate_ts_sdk(entry, auth)
        return ""

    def _generate_python_sdk(self, entry: dict[str, Any], auth: str, retry: str,
                              serialization: str) -> str:
        api_name = entry.get("关联API", "example")
        sdk_code = f'''"""SDK for {api_name} - Auto-generated by SDK Config Service."""

import requests

class {api_name.replace("-", "_").title()}Client:
    def __init__(self, base_url: str, api_key: str):
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key
        self.session = requests.Session()
        self.session.headers.update({{"Authorization": f"Bearer {{api_key}}"}})

    def query(self, params: dict = None) -> dict:
        url = f"{{self.base_url}}/api/{api_name}/query"
        resp = self.session.post(url, json=params or {{}}, timeout=30)
        resp.raise_for_status()
        return resp.json()
'''
        return sdk_code

    def _generate_java_sdk(self, entry: dict[str, Any], auth: str) -> str:
        api_name = entry.get("关联API", "example")
        return f'''package com.example.sdk;

public class {api_name.replace("-", "_")}Client {{
    private final String baseUrl;
    private final String apiKey;

    public {api_name.replace("-", "_")}Client(String baseUrl, String apiKey) {{
        this.baseUrl = baseUrl;
        this.apiKey = apiKey;
    }}

    public String query(String params) {{
        // HTTP client implementation
        return "{{}}";
    }}
}}
'''

    def _generate_ts_sdk(self, entry: dict[str, Any], auth: str) -> str:
        api_name = entry.get("关联API", "example")
        return f'''export class {api_name.replace("-", "_")}Client {{
    private baseUrl: string;
    private apiKey: string;

    constructor(baseUrl: string, apiKey: string) {{
        this.baseUrl = baseUrl;
        this.apiKey = apiKey;
    }}

    async query(params: Record<string, unknown>): Promise<unknown> {{
        const resp = await fetch(`${{this.baseUrl}}/api/{api_name}/query`, {{
            method: 'POST',
            headers: {{ 'Authorization': `Bearer ${{this.apiKey}}` }},
            body: JSON.stringify(params),
        }});
        return resp.json();
    }}
}}
'''

    def run_action(self, entry_id: int, action: str) -> tuple[dict[str, Any] | None, str]:
        entry = store.find(self.MODULE, entry_id)
        if entry is None:
            return None, f"{self.ENTITY} {entry_id} 不存在或已归档"

        if action == "确认发布":
            # 发布时校验API注册状态
            from app.services.data_manager import read_api_snapshot
            api_name = entry.get("关联API", "")
            registry = read_api_snapshot()
            for api_data in (registry.values() if isinstance(registry, dict) else []):
                if isinstance(api_data, dict) and api_data.get("api_name") == api_name:
                    break
            else:
                return None, "关联API尚未注册"

            # 生成SDK代码
            sdk_code = self.generate_sdk_code(entry_id)

        result = super().run_action(entry_id, action)
        from app.services.data_manager import write_module_snapshot
        write_module_snapshot(self.MODULE, self.domain_snapshot())
        return result

    def domain_snapshot(self) -> dict[str, Any]:
        rows = store.rows(self.MODULE)
        sdk_list = []
        for row in rows:
            sdk_list.append({
                "id": row.get("id"),
                "config_no": row.get("配置编号"),
                "api": row.get("关联API"),
                "language": row.get("SDK语言"),
                "template": row.get("生成模板"),
                "auth": row.get("认证方式"),
                "retry": row.get("重试策略"),
                "serialization": row.get("序列化格式"),
                "version": row.get("配置版本"),
                "status": row.get("status"),
            })
        return {
            "module": self.MODULE,
            "entity": self.ENTITY,
            "artifact": f"{self.ENTITY}数据集",
            "count": len(sdk_list),
            "configs": sdk_list,
            "published_count": sum(1 for r in sdk_list if r.get("status") == "已发布"),
        }